// Aggregates results/raw/*.json into results/summary.json and results/RESULTS.md
// (median with min–max across measured runs).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const RAW = 'results/raw';
const read = (f) => JSON.parse(readFileSync(`${RAW}/${f}`, 'utf8'));
const files = readdirSync(RAW);
const env = JSON.parse(readFileSync('results/environment.json', 'utf8'));
const stores = ['rustfs', 'seaweedfs', 'minio'].filter((s) => files.some((f) => f.startsWith(`run-${s}-`)));
const LABEL = { rustfs: 'RustFS', seaweedfs: 'SeaweedFS', minio: 'MinIO' };

const stat = (xs) => {
  const v = [...xs].sort((a, b) => a - b);
  const mid = v.length >> 1;
  const median = v.length % 2 ? v[mid] : (v[mid - 1] + v[mid]) / 2;
  return { median: +median.toFixed(2), min: v[0], max: v.at(-1), n: v.length };
};

/** metric path → (run) => number */
const METRICS = {
  readyMs: (r) => r.readyMs,
  idleAnonMiB: (r) => r.idleAnonMiB,
  peakAnonMiB: (r) => r.peakAnonMiB,
  avgCpuCores: (r) => r.avgCpuCores,
  /** CPU time spent on the whole measured workload (utilization x wall time); the fair "CPU cost" figure. */
  cpuSeconds: (r) => +(r.avgCpuCores * r.wallSeconds).toFixed(1),
  diskMiBAfterOneCopy: (r) => r.diskMiBAfterOneCopy,
  wallSeconds: (r) => r.wallSeconds,
};
for (const sc of ['small-64KiB', 'medium-8MiB', 'multipart-256MiB']) {
  for (const dir of ['put', 'get']) {
    METRICS[`${sc}.${dir}.MiBps`] = (r) => r.scenarios.find((x) => x.name === sc)[dir].MiBps;
    if (sc !== 'multipart-256MiB') {
      METRICS[`${sc}.${dir}.ops`] = (r) => r.scenarios.find((x) => x.name === sc)[dir].ops;
      METRICS[`${sc}.${dir}.p99ms`] = (r) => r.scenarios.find((x) => x.name === sc)[dir].p99ms;
    }
  }
}

const summary = { environment: env, stores: {} };
for (const s of stores) {
  const runs = files.filter((f) => f.startsWith(`run-${s}-`)).map(read);
  const metrics = Object.fromEntries(Object.entries(METRICS).map(([k, f]) => [k, stat(runs.map(f))]));
  const compat = files.includes(`compat-${s}.json`) ? read(`compat-${s}.json`) : {};
  const dur = files.includes(`durability-${s}.json`) ? read(`durability-${s}.json`) : [];
  const durability = dur.reduce((a, c) => ({ cycles: a.cycles + 1, acked: a.acked + c.acked, ok: a.ok + c.ok, missing: a.missing + c.missing, corrupt: a.corrupt + c.corrupt }),
    { cycles: 0, acked: 0, ok: 0, missing: 0, corrupt: 0 });
  summary.stores[s] = { runs: runs.length, metrics, compat, durability, durabilityCycles: dur };
}
writeFileSync('results/summary.json', `${JSON.stringify(summary, null, 2)}\n`);

const fmt = (m, digits = 0) => `${m.median.toFixed(digits)} (${m.min.toFixed(digits)}–${m.max.toFixed(digits)})`;
const row = (label, key, digits) => `| ${label} | ${stores.map((s) => fmt(summary.stores[s].metrics[key], digits)).join(' | ')} |`;
const head = `| | ${stores.map((s) => LABEL[s]).join(' | ')} |\n|---|${stores.map(() => '---').join('|')}|`;
const compatKeys = [...new Set(stores.flatMap((s) => Object.keys(summary.stores[s].compat)))];

const md = `# Results

Median (min–max) over ${Math.min(...stores.map((s) => summary.stores[s].runs))} measured runs per store. Generated by \`node bench/report.mjs\` from \`results/raw\`.
Environment: ${env.host.model} (${env.host.cpu}, ${env.host.memGiB} GiB), ${env.host.os}; Docker ${env.docker.version} VM with ${env.docker.vmCpus} CPUs / ${env.docker.vmMemGiB} GiB; ${env.date.slice(0, 10)}.

## Throughput (MiB/s, higher is better)

${head}
${row('64 KiB PUT', 'small-64KiB.put.MiBps', 1)}
${row('64 KiB GET', 'small-64KiB.get.MiBps', 1)}
${row('8 MiB PUT', 'medium-8MiB.put.MiBps', 1)}
${row('8 MiB GET', 'medium-8MiB.get.MiBps', 1)}
${row('256 MiB multipart PUT', 'multipart-256MiB.put.MiBps', 1)}
${row('256 MiB GET', 'multipart-256MiB.get.MiBps', 1)}

## Latency p99 (ms, lower is better)

${head}
${row('64 KiB PUT p99', 'small-64KiB.put.p99ms', 1)}
${row('64 KiB GET p99', 'small-64KiB.get.p99ms', 1)}
${row('8 MiB PUT p99', 'medium-8MiB.put.p99ms', 1)}
${row('8 MiB GET p99', 'medium-8MiB.get.p99ms', 1)}

## Resources

${head}
${row('Startup: first HTTP response, probe started after docker run (ms, lower bound)', 'readyMs')}
${row('Idle memory, anon (MiB)', 'idleAnonMiB')}
${row('Peak memory under load, anon (MiB)', 'peakAnonMiB')}
${row('CPU time for the measured workload (CPU-seconds)', 'cpuSeconds', 1)}
${row('Average CPU utilization during the workload (cores)', 'avgCpuCores', 2)}
${row('Workload wall time (s)', 'wallSeconds', 1)}
${row('Disk for 607 MiB written once (MiB)', 'diskMiBAfterOneCopy')}

## S3 compatibility

| Check | ${stores.map((s) => LABEL[s]).join(' | ')} |
|---|${stores.map(() => '---').join('|')}|
${compatKeys.map((k) => `| ${k} | ${stores.map((s) => (summary.stores[s].compat[k] ?? 'n/a').startsWith('FAIL') ? `❌ ${summary.stores[s].compat[k].slice(5)}` : '✅').join(' | ')} |`).join('\n')}

## Crash durability (kill -9, restart, verify every acknowledged object)

| | ${stores.map((s) => LABEL[s]).join(' | ')} |
|---|${stores.map(() => '---').join('|')}|
| Cycles | ${stores.map((s) => summary.stores[s].durability.cycles).join(' | ')} |
| Acknowledged writes | ${stores.map((s) => summary.stores[s].durability.acked).join(' | ')} |
| Intact after restart | ${stores.map((s) => summary.stores[s].durability.ok).join(' | ')} |
| Missing | ${stores.map((s) => summary.stores[s].durability.missing).join(' | ')} |
| Corrupt | ${stores.map((s) => summary.stores[s].durability.corrupt).join(' | ')} |
`;
writeFileSync('results/RESULTS.md', md);
console.log(md);
